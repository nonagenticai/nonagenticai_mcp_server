fn resolved(
    auth: SourceAuth,
    token: Option<&str>,
) -> mcp_server_rs::worker::sources::ResolvedSource {
    mcp_server_rs::worker::sources::ResolvedSource {
        source_id: uuid(SOURCE_A),
        owner_tenant_id: uuid(TENANT),
        source_key: "synthetic_source".into(),
        base_url: "https://api.example.test".into(),
        auth,
        token: token.map(str::to_owned),
        idempotency_header: None,
        ca_file: None,
        max_request_bytes: NO_SOURCE_BOUND,
        max_response_bytes: NO_SOURCE_BOUND,
        revision: 1,
        tenant_owned: false,
    }
}

fn adapters(max_ttl: Duration) -> AuthAdapters {
    // Both rustls providers are linked in this test binary; pick one before any client exists.
    mcp_server_rs::install_crypto_provider();
    AuthAdapters::new(reqwest::Client::new(), reqwest::Client::new(), max_ttl)
}

#[tokio::test]
async fn every_auth_kind_is_applied_to_headers_or_query() {
    let adapters = adapters(Duration::from_secs(3_600));

    // Kinds the broker handles itself: no credential is applied.
    for auth in [
        SourceAuth::None,
        SourceAuth::Licence {
            alias: None,
            app_key: APP.into(),
            bundle: None,
            scheme: LicenceScheme::Bearer,
        },
    ] {
        let mut headers = HashMap::new();
        let mut query = HashMap::new();
        assert!(
            adapters
                .apply(&resolved(auth, None), &mut headers, &mut query, None)
                .await
                .expect("nothing to apply")
                .is_empty()
        );
        assert!(headers.is_empty() && query.is_empty());
    }

    let mut headers = HashMap::new();
    let mut query = HashMap::new();
    let secrets = adapters
        .apply(
            &resolved(SourceAuth::StaticBearer, Some("tok")),
            &mut headers,
            &mut query,
            None,
        )
        .await
        .expect("static bearer");
    assert_eq!(headers["Authorization"], "Bearer tok");
    assert_eq!(secrets, ["tok"]);

    let mut headers = HashMap::new();
    adapters
        .apply(
            &resolved(
                SourceAuth::StaticHeader {
                    name: "X-Api-Key".into(),
                },
                Some("tok"),
            ),
            &mut headers,
            &mut HashMap::new(),
            None,
        )
        .await
        .expect("static header");
    assert_eq!(headers["X-Api-Key"], "tok");

    let mut headers = HashMap::new();
    let secrets = adapters
        .apply(
            &resolved(
                SourceAuth::Basic {
                    username: "svc".into(),
                },
                Some("tok"),
            ),
            &mut headers,
            &mut HashMap::new(),
            None,
        )
        .await
        .expect("basic");
    use base64::Engine as _;
    let blob = base64::engine::general_purpose::STANDARD.encode("svc:tok");
    assert_eq!(headers["Authorization"], format!("Basic {blob}"));
    assert_eq!(secrets, ["tok".to_owned(), blob]);

    let mut query = HashMap::new();
    let secrets = adapters
        .apply(
            &resolved(
                SourceAuth::QueryParam {
                    name: "api_key".into(),
                },
                Some("tok/w+1"),
            ),
            &mut HashMap::new(),
            &mut query,
            None,
        )
        .await
        .expect("query param");
    assert_eq!(query["api_key"], "tok/w+1");
    assert_eq!(secrets, ["tok/w+1", "tok%2Fw%2B1"]);

    // A kind that needs a secret without one cannot be applied.
    assert!(matches!(
        adapters
            .apply(
                &resolved(SourceAuth::StaticBearer, None),
                &mut HashMap::new(),
                &mut HashMap::new(),
                None,
            )
            .await,
        Err(AuthError::Failed)
    ));
}

