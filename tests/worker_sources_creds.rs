#[test]
fn every_auth_kind_parses_exactly_as_the_contract_declares() {
    assert_eq!(
        SourceAuth::parse(&json!({"kind": "none"})).unwrap(),
        SourceAuth::None
    );
    assert_eq!(
        SourceAuth::parse(&json!({
            "kind": "licence", "app_key": "care-bus", "bundle": "care_bus_v1",
            "scheme": "x_tenant_id_bearer"
        }))
        .unwrap(),
        SourceAuth::Licence {
            alias: None,
            app_key: "care-bus".into(),
            bundle: Some("care_bus_v1".into()),
            scheme: LicenceScheme::XTenantIdBearer,
        }
    );
    assert_eq!(
        SourceAuth::parse(&json!({"kind": "static_bearer"})).unwrap(),
        SourceAuth::StaticBearer
    );
    assert_eq!(
        SourceAuth::parse(&json!({"kind": "static_header", "header": "X-Api-Key"})).unwrap(),
        SourceAuth::StaticHeader {
            name: "X-Api-Key".into()
        }
    );
    assert_eq!(
        SourceAuth::parse(&json!({"kind": "query_param", "param": "api_key"})).unwrap(),
        SourceAuth::QueryParam {
            name: "api_key".into()
        }
    );
    assert_eq!(
        SourceAuth::parse(&json!({"kind": "basic", "username": "svc"})).unwrap(),
        SourceAuth::Basic {
            username: "svc".into()
        }
    );
    assert_eq!(
        SourceAuth::parse(&json!({
            "kind": "oauth2_client_credentials", "token_url": "https://auth.example.test/token",
            "client_id": "svc", "scope": "read write", "client_auth": "post"
        }))
        .unwrap(),
        SourceAuth::OAuth2ClientCredentials {
            token_url: "https://auth.example.test/token".into(),
            client_id: "svc".into(),
            scopes: Some("read write".into()),
            audience: None,
            client_auth: ClientAuth::Post,
        }
    );
    // The contract's refusals: a reserved header, an unknown field, an insecure token URL.
    assert!(
        SourceAuth::parse(&json!({"kind": "static_header", "header": "x-idempotency-key"}))
            .is_err()
    );
    assert!(SourceAuth::parse(&json!({"kind": "none", "extra": 1})).is_err());
    assert!(
        SourceAuth::parse(&json!({
            "kind": "oauth2_client_credentials", "token_url": "http://auth.example.test/token",
            "client_id": "svc"
        }))
        .is_err()
    );
    assert!(SourceAuth::parse(&json!({"kind": "licence", "app_key": "MCP"})).is_err());
}

