#[tokio::test]
async fn the_minter_posts_the_oauth_and_mint_requests_the_reference_makes() {
    let local = authority_server(Authority::new()).await;
    let secret = secret_file("client-secret\n");
    let minter = build_minter(&local, &secret.path, Some(REFUSED_APP));
    assert!(!minter.gateway_credentials());
    minter.read().expect("secret file present");

    let token = minter
        .resolve(&uuid(TENANT), &uuid(PROFILE), &reference())
        .await
        .expect("the minted credential resolves");
    assert_eq!(token, "minted-token");
    assert_eq!(
        minter
            .licence_id(&uuid(TENANT), APP, None)
            .await
            .expect("id"),
        uuid(LICENCE)
    );

    let token_requests = local.authority.token_requests.lock().expect("requests");
    assert_eq!(
        token_requests.as_slice(),
        ["grant_type=client_credentials&client_id=minter-client&client_secret=client-secret"]
    );
    let mints = local.authority.mint_requests.lock().expect("requests");
    assert_eq!(mints.len(), 1, "one mint for two resolves: {mints:?}");
    assert_eq!(mints[0]["tenant"], json!(TENANT));
    assert_eq!(mints[0]["query"]["app"], json!(APP));
    assert_eq!(mints[0]["query"]["ttl_minutes"], json!("15"));
    assert_eq!(mints[0]["authorization"], json!("Bearer client-token"));
    let introspections = local
        .authority
        .introspect_requests
        .lock()
        .expect("requests");
    assert_eq!(introspections.len(), 1, "one proof per fresh mint");
    assert_eq!(
        introspections[0],
        json!({"token": "minted-token", "app": APP})
    );
}

