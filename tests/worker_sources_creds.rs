struct BundleFile {
    path: PathBuf,
}

impl Drop for BundleFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.path);
    }
}

fn bundle_file(payload: &Value, mode: u32) -> BundleFile {
    static NEXT: AtomicUsize = AtomicUsize::new(0);
    let path = std::env::temp_dir().join(format!(
        "mcp-bundle-{}-{}.json",
        std::process::id(),
        NEXT.fetch_add(1, Ordering::Relaxed)
    ));
    std::fs::write(&path, serde_json::to_vec(payload).expect("bundle json")).expect("write");
    use std::os::unix::fs::PermissionsExt as _;
    std::fs::set_permissions(&path, std::fs::Permissions::from_mode(mode)).expect("chmod");
    BundleFile { path }
}

fn entry(alias: &str, license: &str, token: &str) -> Value {
    json!({
        "tenant_id": TENANT,
        "profile_id": PROFILE,
        "service": "synthetic_service",
        "alias": alias,
        "license_id": license,
        "app_key": APP,
        "token": token,
        "oauth_bearer": "upstream-oauth",
    })
}

fn bundle(entries: Vec<Value>) -> Value {
    json!({"schema_version": 1, "entries": entries})
}

#[tokio::test]
async fn a_valid_bundle_resolves_its_one_entry() {
    let file = bundle_file(
        &bundle(vec![entry("synthetic", LICENCE, "bundle-token")]),
        0o600,
    );
    let resolver = FileResolver::new(&file.path);
    assert!(resolver.gateway_credentials());
    resolver.read().expect("valid bundle");
    assert_eq!(
        resolver
            .resolve(&uuid(TENANT), &uuid(PROFILE), &reference())
            .await
            .expect("resolves"),
        "bundle-token"
    );
    assert_eq!(
        resolver
            .entry(&uuid(TENANT), &uuid(PROFILE), &reference())
            .await
            .expect("entry")
            .oauth_bearer
            .as_deref(),
        Some("upstream-oauth")
    );
    // The file resolver never mints.
    assert!(matches!(
        resolver.mint(&uuid(TENANT), APP, None).await,
        Err(CredentialError::Denied("mint unavailable"))
    ));
}

