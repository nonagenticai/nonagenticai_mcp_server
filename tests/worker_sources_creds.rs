#[tokio::test]
async fn an_oauth_token_is_fetched_once_reused_and_evicted() {
    let local = authority_server(Authority::new()).await;
    let adapters = adapters(Duration::from_secs(3_600));
    let source = resolved(
        oauth_source(&format!("{}/token", local.base)),
        Some("client-secret"),
    );
    let mut headers = HashMap::new();
    let secrets = adapters
        .apply(&source, &mut headers, &mut HashMap::new(), None)
        .await
        .expect("oauth applies");
    assert_eq!(headers["Authorization"], "Bearer client-token");
    assert_eq!(secrets, ["client-secret", "client-token"]);
    adapters
        .apply(&source, &mut HashMap::new(), &mut HashMap::new(), None)
        .await
        .expect("cached");
    assert_eq!(
        local.authority.token_calls.load(Ordering::SeqCst),
        1,
        "the token is reused"
    );
    adapters.evict(&source);
    adapters
        .apply(&source, &mut HashMap::new(), &mut HashMap::new(), None)
        .await
        .expect("refetched after eviction");
    assert_eq!(local.authority.token_calls.load(Ordering::SeqCst), 2);
    let requests = local.authority.token_requests.lock().expect("requests");
    assert_eq!(
        requests[0], "grant_type=client_credentials&scope=read",
        "basic client authentication keeps the credentials out of the body"
    );
}

#[tokio::test]
async fn an_oauth_token_lifetime_is_capped_by_the_configured_maximum() {
    let local = authority_server(Authority::new()).await;
    let now = Arc::new(AtomicI64::new(1_000));
    let clock: Clock = {
        let now = now.clone();
        Arc::new(move || now.load(Ordering::SeqCst) as f64)
    };
    // The server grants 300 s; the configured maximum is 60 s, so the cache entry lives
    // 60 - 30 (skew) = 30 s.
    let adapters = adapters(Duration::from_secs(60)).with_clock(clock);
    let source = resolved(
        oauth_source(&format!("{}/token", local.base)),
        Some("client-secret"),
    );
    for _ in 0..2 {
        adapters
            .apply(&source, &mut HashMap::new(), &mut HashMap::new(), None)
            .await
            .expect("applies");
    }
    assert_eq!(local.authority.token_calls.load(Ordering::SeqCst), 1);
    now.store(1_029, Ordering::SeqCst);
    adapters
        .apply(&source, &mut HashMap::new(), &mut HashMap::new(), None)
        .await
        .expect("still cached");
    assert_eq!(local.authority.token_calls.load(Ordering::SeqCst), 1);
    now.store(1_031, Ordering::SeqCst);
    adapters
        .apply(&source, &mut HashMap::new(), &mut HashMap::new(), None)
        .await
        .expect("refreshed");
    assert_eq!(
        local.authority.token_calls.load(Ordering::SeqCst),
        2,
        "the cap, not the server's 300 s, decides expiry"
    );
}

