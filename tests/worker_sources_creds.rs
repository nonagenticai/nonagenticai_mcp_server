//! Ported from `src/sources/registry.py`, `src/sources/crypto.py`, `src/credentials/resolver.py`,
//! `src/credentials/minter.py` and `src/broker/auth.py`. The sealed-secret fixture
//! (`fixtures/phase3b/crypto.json`) was produced by the pinned Python implementation, so the
//! registry test decrypts the oracle's ciphertext rather than a Rust round-trip. The minter and
