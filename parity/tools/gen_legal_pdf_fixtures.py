#!/usr/bin/env python3
"""Generate the legal-PDF parity fixtures from the PINNED reference, not from assumptions.

The three PDF-reading legal tools (`legal_eli_act_text`, `legal_duw_document`,
`legal_uokik_document`) reproduce `src/builtin/legal/pdf_text.py` at the pinned archive SHA.
Byte parity is the only acceptable outcome, so the fixtures are generated by that module itself:

    python parity/tools/gen_legal_pdf_fixtures.py [--check]

* `tests/fixtures/legal_pdf/*.pdf` — deterministic documents authored here (a minimal PDF
  writer, no dependency) plus any checked-in public documents. They cover the layout rules the
  reference implements: raised smaller superscripts, the bracketed `Art. 449[1]` form, page
  furniture, hyphenation, TJ kerning, a Form XObject, a scaled CTM, Differences/ToUnicode font
  encodings and the page cap.
* `tests/fixtures/legal_pdf/oracle.json` — for every PDF: its SHA-256, the reference's final
  text, and the **visitor stream** pypdf hands to `pdf_text.py` (per page: the text, cm, tm and
  font size of every callback, in order). The Rust port asserts the stream record-for-record and
  then the text byte-for-byte, so a divergence is localised to the parser or to the layout.

`--check` regenerates in memory and fails if a committed file would change (the CI-safe gate).

Requires the archive's venv (pypdf 6.21.4) and `PYTHONPATH` pointing at it; see the header of
`parity/README.md`.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import sys
from pathlib import Path
from typing import Callable

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "tests" / "fixtures" / "legal_pdf"

ARCHIVE = Path(
    os.environ.get(
        "LEGAL_PDF_ORACLE",
        Path.home() / "Movies/nonagenticai/nonagenticai_mcp_server-python-archive",
    )
)

# ── a minimal, deterministic PDF writer (no dependencies) ───────────────────────────────────


def escape(data: bytes) -> bytes:
    return data.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)")


class Pdf:
    """Objects in order; `build` writes one uncompressed PDF with a correct xref."""

    def __init__(self) -> None:
        self.objects: list[bytes] = []

    def add(self, body: bytes) -> int:
        self.objects.append(body)
        return len(self.objects)  # 1-based object numbers

    def reserve(self) -> int:
        self.objects.append(b"")
        return len(self.objects)

    def fill(self, number: int, body: bytes) -> None:
        self.objects[number - 1] = body

    def build(self) -> bytes:
        out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
        offsets = [0]
        for number, body in enumerate(self.objects, start=1):
            offsets.append(len(out))
            out += b"%d 0 obj\n" % number + body + b"\nendobj\n"
        xref = len(out)
        out += b"xref\n0 %d\n" % (len(self.objects) + 1)
        out += b"0000000000 65535 f \n"
        for offset in offsets[1:]:
            out += b"%010d 00000 n \n" % offset
        out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
            len(self.objects) + 1,
            xref,
        )
        return bytes(out)


def stream(body: bytes) -> bytes:
    return b"<< /Length %d >>\nstream\n" % len(body) + body + b"\nendstream"


def font_winansi() -> bytes:
    return b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"


def font_differences() -> bytes:
    # Codes 1..8 name Polish glyphs; pypdf maps glyph names to Unicode (the reference's
    # `/Differences` path), which a WinAnsi font cannot represent.
    return (
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding << "
        b"/Type /Encoding /Differences [1 /aogonek /cacute /eogonek /lslash /nacute "
        b"/oacute /sacute /zdot] >> >>"
    )


def font_tounicode(cmap: int) -> bytes:
    return (
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding "
        b"/ToUnicode %d 0 R >>" % cmap
    )


def content(runs: list[bytes]) -> bytes:
    return b"\n".join(runs)


def run(text: bytes, size: float, x: float, y: float, font: str = "F1") -> bytes:
    return b"BT /%s %s Tf 1 0 0 1 %s %s Tm (%s) Tj ET" % (
        font.encode(),
        num(size),
        num(x),
        num(y),
        escape(text),
    )


def num(value: float) -> bytes:
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return (text or "0").encode()


def page(pdf: Pdf, body: bytes, resources: bytes) -> int:
    contents = pdf.add(stream(body))
    return pdf.add(
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources " + resources + b" /Contents %d 0 R >>" % contents
    )


def assemble(build: Callable[[Pdf], list[int]]) -> bytes:
    """Run one document builder: object 1 is the catalog, 2 the page tree."""
    pdf = Pdf()
    pdf.add(b"")  # 1: catalog
    pdf.add(b"")  # 2: pages
    pages = build(pdf)
    pdf.fill(1, b"<< /Type /Catalog /Pages 2 0 R >>")
    kids = b" ".join(b"%d 0 R" % p for p in pages)
    pdf.fill(2, b"<< /Type /Pages /Kids [" + kids + b"] /Count %d >>" % len(pages))
    return pdf.build()


# ── the fixture documents ───────────────────────────────────────────────────────────────────


def layout_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        resources = b"<< /Font << /F1 %d 0 R /F2 %d 0 R >> >>" % (
            pdf.add(font_winansi()),
            pdf.add(font_winansi()),
        )
        body = content(
            [
                # A raised, smaller run after an alphanumeric chunk: "Art. 61^1".
                run(b"Art. 61", 10, 72, 700),
                run(b"1", 6, 101.46, 703, "F2"),
                run(b".", 10, 104.8, 700),
                # A new line (delta -20 > 1): "Art. 611.".
                run(b"Art. 611.", 10, 72, 680),
                # A raised run at the SAME size is no superscript: the 3pt jump is a new line.
                run(b"same", 10, 72, 660),
                run(b"size", 10, 100, 663),
                # A small run raised by 9pt exceeds the 8pt ceiling: also a new line.
                run(b"far", 6, 72, 640),
                # A small run raised by 0.3pt is below the 0.5pt floor: same line, no caret.
                run(b"near", 10, 72, 620),
                run(b"low", 6, 100, 620.3),
                # The caret is inserted only after an alphanumeric character: after "." none.
                run(b"453.", 10, 72, 600),
                run(b"2", 6, 91.46, 603),
            ]
        )
        return [page(pdf, body, resources)]

    return assemble(build)


def furniture_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        resources = b"<< /Font << /F1 %d 0 R >> >>" % pdf.add(font_winansi())
        body = content(
            [
                run(b"\xa9 Kancelaria Sejmu 2024", 8, 72, 740),
                run(b"Dziennik Ustaw \x96 12 \x96 Poz. 345", 8, 72, 730),
                run(b"2024-01-31", 8, 72, 720),
                run(b"s. 5/10", 8, 72, 710),
                # Body: the bracketed superscript form the reference rewrites.
                run(b"Art. 449[1].", 10, 72, 690),
                # A hyphen at a line end before a lowercase letter is removed ("wycho-\nwania").
                run(b"wycho-", 10, 72, 670),
                run(b"wania", 10, 72, 650),
                # ... but not before an uppercase word ("kontroli-\nNaczelnego").
                run(b"kontroli-", 10, 72, 630),
                run(b"Naczelnego", 10, 72, 610),
            ]
        )
        return [page(pdf, body, resources)]

    return assemble(build)


def kerning_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        resources = b"<< /Font << /F1 %d 0 R >> >>" % pdf.add(font_winansi())
        body = content(
            [
                # One text object, two show operators: the visitor sees ONE chunk ("Ala ma").
                b"BT /F1 10 Tf 1 0 0 1 72 700 Tm (Ala) Tj ( ma) Tj ET",
                # TJ: a large negative adjustment inserts a space, a small one does not — the
                # exact threshold is pypdf's own (a function of the font's space width).
                b"BT /F1 10 Tf 1 0 0 1 72 680 Tm [(kot) -1000 (ala)] TJ ET",
                b"BT /F1 10 Tf 1 0 0 1 72 660 Tm [(kot) -50 (ala)] TJ ET",
                # A scaled CTM: size and y are computed through cm[3]/cm[5].
                b"q 2 0 0 2 10 20 cm BT /F1 10 Tf 1 0 0 1 72 300 Tm (scaled) Tj ET Q",
            ]
        )
        return [page(pdf, body, resources)]

    return assemble(build)


def form_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        font = pdf.add(font_winansi())
        # A Form XObject with its own text; `Do` flushes, emits a newline and recurses.
        form = pdf.add(
            b"<< /Type /XObject /Subtype /Form /BBox [0 0 612 792] "
            b"/Resources << /Font << /F1 %d 0 R >> >> /Length %d >>\nstream\n"
            % (font, len(b"BT /F1 10 Tf 1 0 0 1 20 20 Tm (inside) Tj ET"))
            + b"BT /F1 10 Tf 1 0 0 1 20 20 Tm (inside) Tj ET"
            + b"\nendstream"
        )
        resources = b"<< /Font << /F1 %d 0 R >> /XObject << /Fm1 %d 0 R >> >>" % (font, form)
        body = content(
            [
                run(b"before", 10, 72, 700),
                b"/Fm1 Do",
                run(b"after", 10, 72, 680),
            ]
        )
        return [page(pdf, body, resources)]

    return assemble(build)


def pages_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        resources = b"<< /Font << /F1 %d 0 R >> >>" % pdf.add(font_winansi())
        return [
            page(pdf, run(b"first page", 10, 72, 700), resources),
            page(pdf, run(b"second page", 10, 72, 700), resources),
            page(pdf, run(b"third page", 10, 72, 700), resources),
        ]

    return assemble(build)


def unicode_pdf() -> bytes:
    def build(pdf: Pdf) -> list[int]:
        cmap = pdf.add(
            stream(
                b"/CIDInit /ProcSet findresource begin\n"
                b"12 dict begin\nbegincmap\n"
                b"/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def\n"
                b"/CMapName /Adobe-Identity-UCS def\n/CMapType 2 def\n"
                b"1 begincodespacerange\n<00> <ff>\nendcodespacerange\n"
                b"2 beginbfchar\n<41> <0105>\n<42> <0119>\nendbfchar\n"
                b"endcmap\nCMapName currentdict /CMap defineresource pop\nend\nend"
            )
        )
        differences = pdf.add(font_differences())
        mapped = pdf.add(font_tounicode(cmap))
        resources = b"<< /Font << /F1 %d 0 R /F2 %d 0 R /F3 %d 0 R >> >>" % (
            pdf.add(font_winansi()),
            differences,
            mapped,
        )
        body = content(
            [
                # Differences: codes 1..8 are the Polish glyphs a WinAnsi font cannot carry.
                b"BT /F2 10 Tf 1 0 0 1 72 700 Tm (\x01\x02\x03\x04\x05\x06\x07\x08) Tj ET",
                # ToUnicode: A -> U+0105, B -> U+0119.
                b"BT /F3 10 Tf 1 0 0 1 72 680 Tm (AB) Tj ET",
                # A literal WinAnsi byte that also maps through ToUnicode unchanged.
                b"BT /F3 10 Tf 1 0 0 1 72 660 Tm (C) Tj ET",
            ]
        )
        return [page(pdf, body, resources)]

    return assemble(build)


DOCUMENTS = {
    "layout.pdf": layout_pdf,
    "furniture.pdf": furniture_pdf,
    "kerning.pdf": kerning_pdf,
    "form.pdf": form_pdf,
    "pages.pdf": pages_pdf,
    "unicode.pdf": unicode_pdf,
}


# ── the oracle ─────────────────────────────────────────────────────────────────────────────


def load_oracle():
    sys.path.insert(0, str(ARCHIVE))
    from src.builtin.legal.pdf_text import pdf_to_text  # noqa: PLC0415

    return pdf_to_text


def visitor_stream(data: bytes) -> list[list[dict]]:
    """The exact callbacks `pdf_text.py` receives, per page (pypdf 6.21.4)."""
    from pypdf import PdfReader  # noqa: PLC0415

    reader = PdfReader(io.BytesIO(data))
    pages: list[list[dict]] = []
    for page in reader.pages:
        calls: list[dict] = []

        def visit(text, cm, tm, font_dict, font_size, calls=calls):
            calls.append(
                {
                    "text": text,
                    "cm": [float(v) for v in cm],
                    "tm": [float(v) for v in tm],
                    "size": float(font_size),
                }
            )

        page.extract_text(visitor_text=visit)
        pages.append(calls)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a fixture would change")
    args = parser.parse_args()

    pdf_to_text = load_oracle()
    rendered: dict[str, bytes] = {}
    oracle: dict[str, dict] = {}

    for name, builder in DOCUMENTS.items():
        data = builder()
        rendered[name] = data
        text = pdf_to_text(data)
        entry = {
            "sha256": hashlib.sha256(data).hexdigest(),
            "text": text,
            "visitors": visitor_stream(data),
        }
        # The page cap's closing line, exactly as the reference appends it.
        total = len(entry["visitors"])
        if total > 1:
            entry["text_max2"] = pdf_to_text(data, 2)
        oracle[name] = entry

    payload = json.dumps({"pdfs": oracle}, indent=1, sort_keys=True, ensure_ascii=False) + "\n"
    payload_bytes = payload.encode("utf-8")

    OUT.mkdir(parents=True, exist_ok=True)
    changed: list[str] = []
    for name, data in rendered.items():
        path = OUT / name
        if path.exists() and path.read_bytes() == data:
            continue
        changed.append(str(path))
        if not args.check:
            path.write_bytes(data)
    oracle_path = OUT / "oracle.json"
    if not oracle_path.exists() or oracle_path.read_bytes() != payload_bytes:
        changed.append(str(oracle_path))
        if not args.check:
            oracle_path.write_bytes(payload_bytes)

    if args.check and changed:
        print("fixtures are stale; regenerate with this script:", file=sys.stderr)
        for path in changed:
            print(f"  {path}", file=sys.stderr)
        return 1
    for path in changed:
        print(f"wrote {path}")
    if not changed:
        print("fixtures already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
