//! The tenant builder's pure domain: OpenAPI documents in, draft tool packages and manifests out.
//!
//! Ported from the reference's `src/builder/{models,spec,packaging,openapi}.py`. No database and
//! no HTTP: the document fetch itself is the reference's `DocumentFetcher` protocol, ported in
//! [`service`] with the broker's pinned-egress transport behind it.
//!
//! # Where the port cannot be literal
//!
//! - **Dict ordering.** Python preserves JSON object order and the importers depend on it
//!   (`properties` iteration, `$defs` insertion, media-type preference). `serde_json` is built
//!   with `preserve_order`, so a parsed document keeps the same order. The one place the
//!   reference sorts explicitly, `sorted(doc["paths"])`, is sorted here too (byte order equals
//!   Python's code-point order).
//! - **Regex dialect.** Rust's regex crate has no lookbehind and no backtracking. `snake`'s
//!   `(?<=[a-z0-9])([A-Z])` is a character scan; the `$defs` reachability scan still serializes
//!   the def to JSON and matches the reference's pattern. The deny list's `*` patterns are
//!   literal-segment globs; Python's `.` does not cross a newline and its `$` also matches before
//!   a trailing newline, a distinction not reproduced (such a path cannot become a manifest).
//!   Rust's `\d` matches Unicode decimal digits exactly as Python's does.
//! - **Crashes become refusals.** A few malformed shapes raise an uncaught `TypeError` in the
//!   reference (`requestBody` that is not an object, a truthy non-list `parameters`/override,
//!   a non-string `format` or `required` entry, a stored `ops.py` without an `OPS = ` table).
//!   They are never panics here: the same refusal message is produced where one exists,
//!   otherwise the value is dropped or the manifest validation refuses it.
//! - **Error text.** Cross-field refusals keep the reference's messages. Generic field errors
//!   and manifest validation are serde/`CatalogError` messages, not Pydantic's, and
//!   `BuilderInputError` is defined in the reference's `service.py`, not in `models.py`.
//! - **Identities.** Operation ids are `uuid::Uuid::now_v7()` (the crate's existing dependency)
//!   where the reference calls `uuid7()`. `parse_ops` validates the stored ids as `Uuid7` and
//!   versions as `PositiveVersion` at parse time; the reference's `UUID`/`int` accept more
//!   shapes and rely on later model validation.
//! - **Embedded host file.** The Rust checkout has no `toolkits/_kit/kit.py`, so the host file's
//!   bytes are embedded in [`packaging`]; `ops.py` is generated by a writer that reproduces
//!   Python's `json.dumps(indent=2, sort_keys=True)` escaping rather than serde's pretty
//!   printer.
//! - **Spec bytes.** `parse_document` reproduces `json.loads(bytes)` BOM detection for UTF-8,
//!   UTF-16 and UTF-32. serde_json's nesting limit (128) is lower than Python's recursion limit,
//!   and it refuses the `NaN`/`Infinity` literals and out-of-range numbers Python's `json`
//!   accepts, so those documents are refused as "not JSON" rather than per operation.

